// A faster drop-in for makefun-site 1.0.0 (MIT), the reference program of
// site-generator-speed-01. Written fresh for this entry: it re-implements
// makefun-site's own front matter, template dialect, Markdown subset, slug
// rule and report exactly as its README and code state them, but with the
// hot paths rewritten — a single-pass Markdown renderer that never builds
// token objects, an inline renderer that jumps from one special character
